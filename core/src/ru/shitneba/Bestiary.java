    public static Entry get(String id) { for (Entry e : ALL) if (e.id.equals(id)) return e; return null; }

    public static int kills(String id) {
        Float v = G.SV.stats.get("e_" + id);
        if (v == null) v = G.SV.stats.get(G.D.get("BOSS_INFO").has(id) ? "b_" + id : "k_" + id);
        return v == null ? 0 : Math.round(v);
    }

    public static boolean seen(String id) { return G.SV.seen.contains(id) || kills(id) > 0; }

    /** Отметить, что враг встречен. true — запись открылась впервые. */
    public static boolean see(String id) {
        if (get(id) == null || G.SV.seen.contains(id)) return false;
        G.SV.seen.add(id);
        return true;
    }

    public static int seenCount() { int n = 0; for (Entry e : ALL) if (seen(e.id)) n++; return n; }

